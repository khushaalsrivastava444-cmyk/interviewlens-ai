class DeterministicTfidfEmbeddingProvider:
    """
    Sublinear TF-IDF vectorizer that creates normalized dense embedding vectors.
    100% deterministic, ultra-fast (sub-millisecond), zero GPU or model download dependencies.
    """
    def __init__(self, corpus_texts: List[str]):
        self.vectorizer = TfidfVectorizer(
            ngram_range=(1, 2),
            sublinear_tf=True,
            norm="l2",
            stop_words="english",
        )
        self.vectorizer.fit(corpus_texts)
        self.dimension = len(self.vectorizer.get_feature_names_out())

    def encode(self, texts: List[str]) -> np.ndarray:
        """Transform input texts into L2-normalized dense feature vectors."""
        sparse_vecs = self.vectorizer.transform(texts)
        return sparse_vecs.toarray()


class HybridRAGEngine:
    def __init__(self):
        self.chunks: List[KnowledgeChunk] = []
        self._initialize_corpus()

    def _initialize_corpus(self):
        """Load and vectorize authoritative knowledge base."""
        all_texts = [f"{item['title']} {item['content']} {' '.join(item['key_mechanisms'])}" for item in AUTHORITATIVE_CORPUS]
        self.embedding_provider = DeterministicTfidfEmbeddingProvider(all_texts)

        for item in AUTHORITATIVE_CORPUS:
            full_text = f"{item['title']} {item['content']} {' '.join(item['key_mechanisms'])}"
            vec = self.embedding_provider.encode([full_text])[0].tolist()
            chunk = KnowledgeChunk(
                id=item["id"],
                category=item["category"],
                topic=item["topic"],
                title=item["title"],
                content=item["content"],
                key_mechanisms=item["key_mechanisms"],
                vector=vec,
            )
            self.chunks.append(chunk)

    def retrieve(
        self,
        query: str,
        category: Optional[str] = None,
        top_k: int = 3,
        alpha: float = 0.65,  # 0.65 dense vector weight, 0.35 lexical overlap weight
    ) -> List[RetrievalResult]:
        """
        Execute hybrid retrieval combining dense cosine similarity with sparse lexical token matching.
        """
        if not query.strip():
            return []

        # Filter candidates by category if specified
        candidates = self.chunks
        if category:
            cat_norm = category.lower().replace("-", "_").replace(" ", "_")
            filtered = [c for c in self.chunks if c.category == cat_norm]
            if filtered:
                candidates = filtered

        # 1. Dense Semantic Cosine Similarity
        query_vec = self.embedding_provider.encode([query])  # shape (1, D)
        candidate_vecs = np.array([c.vector for c in candidates])  # shape (N, D)

        dense_scores = cosine_similarity(query_vec, candidate_vecs)[0]  # shape (N,)

        # 2. Sparse Lexical Token Overlap (BM25 surrogate)
        query_tokens = set(re.findall(r"\b\w{3,}\b", query.lower()))
        results: List[RetrievalResult] = []

        for idx, chunk in enumerate(candidates):
            chunk_tokens = set(re.findall(r"\b\w{3,}\b", chunk.content.lower()))
            overlap_count = len(query_tokens.intersection(chunk_tokens))
            lexical_score = overlap_count / max(len(query_tokens), 1)

            dense_score = float(dense_scores[idx])
            hybrid_score = round(alpha * dense_score + (1.0 - alpha) * lexical_score, 4)

            results.append(
                RetrievalResult(
                    chunk_id=chunk.id,
                    category=chunk.category,
                    topic=chunk.topic,
                    title=chunk.title,
                    content=chunk.content,
                    similarity_score=round(dense_score, 4),
                    lexical_score=round(lexical_score, 4),
                    hybrid_score=hybrid_score,
                    key_mechanisms=chunk.key_mechanisms,
                )
            )

        # Sort by hybrid score descending
        results.sort(key=lambda r: r.hybrid_score, reverse=True)
        return results[:top_k]

    def ground_evaluation(
        self,
        candidate_answer: str,
        question_text: str,
        category: str,
    ) -> GroundingEvaluation:
        """
        Compare candidate's explanation against top authoritative reference chunks.
        Calculates semantic coverage, verifies expected technical mechanisms, and cites authoritative references.
        """
        retrieved_chunks = self.retrieve(
            query=f"{question_text} {candidate_answer}",
            category=category,
            top_k=2,
        )

        if not retrieved_chunks:
            return GroundingEvaluation(
                semantic_coverage=0.5,
                covered_mechanisms=[],
                omitted_mechanisms=[],
                authoritative_citations=[],
                factual_consistency_feedback="No authoritative reference found for direct grounding.",
            )

        # Evaluate candidate against key mechanisms
        answer_lower = candidate_answer.lower()
        all_expected_mechanisms = []
        for c in retrieved_chunks:
            all_expected_mechanisms.extend(c.key_mechanisms)

        covered = []
        omitted = []
        for mech in all_expected_mechanisms:
            mech_words = [w for w in re.findall(r"\b\w{4,}\b", mech.lower()) if w not in ["only", "with", "from"]]
            matched = any(w in answer_lower for w in mech_words)
            if matched:
                if mech not in covered:
                    covered.append(mech)
            else:
                if mech not in omitted:
                    omitted.append(mech)

        coverage_ratio = len(covered) / max(len(all_expected_mechanisms), 1)
        semantic_coverage = round(min(1.0, max(0.1, coverage_ratio)), 2)

        citations = [f"{c.title} ({c.topic})" for c in retrieved_chunks]

        if coverage_ratio >= 0.7:
            feedback = "Candidate answer is strongly grounded in core technical principles and avoids speculative errors."
        elif coverage_ratio >= 0.4:
            feedback = f"Answer correctly touches on {len(covered)} principles, but omitted key mechanics: {', '.join(omitted[:2])}."
        else:
            feedback = f"Low factual grounding. Expected discussion of authoritative mechanics: {', '.join(omitted[:3])}."

        return GroundingEvaluation(
            semantic_coverage=semantic_coverage,
            covered_mechanisms=covered,
            omitted_mechanisms=omitted,
            authoritative_citations=citations,
            factual_consistency_feedback=feedback,
        )


