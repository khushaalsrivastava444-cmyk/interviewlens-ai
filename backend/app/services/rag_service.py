class KnowledgeChunk(BaseModel):
    id: str
    category: str
    topic: str
    title: str
    content: str
    key_mechanisms: List[str]
    vector: Optional[List[float]] = None


class RetrievalResult(BaseModel):
    chunk_id: str
    category: str
    topic: str
    title: str
    content: str
    similarity_score: float
    lexical_score: float
    hybrid_score: float
    key_mechanisms: List[str]


class GroundingEvaluation(BaseModel):
    semantic_coverage: float = Field(..., ge=0.0, le=1.0)
    covered_mechanisms: List[str] = []
    omitted_mechanisms: List[str] = []
    authoritative_citations: List[str] = []
    factual_consistency_feedback: str


